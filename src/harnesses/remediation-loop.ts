    '            const statusText = validationPassed && newSha',
    "              ? 'Fixes Applied'",
    '              : hasChanges',
    "                ? 'Fixes Failed Validation'",
    "                : 'No Changes Made';",
    '',
    "            const changedFiles = (process.env.CHANGED_FILES || '').trim();",
    '            const filesSection = changedFiles ? [',
